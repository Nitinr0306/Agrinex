--     resources between 2025-10-14 and 2026-10-14 (236,368 records), plus Sindhudurg from the Agmarknet 2.0 district
--     master. Exact LGD names map directly; every other spelling is mapped only where the markets reported under it
--     name the sub-districts of exactly that LGD district. Agmarknet master entries that never occur in the feed
--     ('Osmanabad', and the non-district entries 'Bandra(E)' and 'Murum') stay unmapped (section 3.2);
--   * localities: the LGD sub-districts, with no coordinates (ADR-0014 item 1);
--   * name_mr of the state: the LGD local-language name; name_hi is not seeded (no reviewed source; ADR-0015).
