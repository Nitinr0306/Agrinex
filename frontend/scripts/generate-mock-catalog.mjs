/**
 * Generates lib/mocks/catalog.generated.ts from the synthetic mock files (__mocks__/api/*.json) and the route
 * table of contracts/openapi.yaml, so mock mode (spec §44) serves exactly the files that the contract tests
 * validate. Run with `npm run generate:mocks` after a contract or mock change (spec §41 step 4).
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mockDir = join(root, "__mocks__", "api");
const contract = parse(readFileSync(join(root, "..", "contracts", "openapi.yaml"), "utf8"));

const files = readdirSync(mockDir).filter((name) => name.endsWith(".json")).sort();
const operations = {};
for (const [path, item] of Object.entries(contract.paths)) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const operation = item[method];
    if (operation) {
      operations[operation.operationId] = { method: method.toUpperCase(), path: path.replace(/\{(\w+)\}/g, ":$1") };
    }
  }
}

const lines = [
  "// GENERATED by scripts/generate-mock-catalog.mjs from __mocks__/api and contracts/openapi.yaml. Do not edit.",
  "// SYNTHETIC TEST DATA ONLY (ADR-0028): never shown as real government data.",
  'import type { MockEnvelope } from "./envelope";',
  ...files.map((name, index) => `import m${index} from "@/__mocks__/api/${name}";`),
  "",
  "export const MOCK_FILES: ReadonlyArray<{ file: string; envelope: MockEnvelope }> = [",
  ...files.map((name, index) => `  { file: ${JSON.stringify(name.replace(/\.json$/, ""))}, envelope: m${index} as MockEnvelope },`),
  "];",
  "",
  "export const OPERATIONS: Readonly<Record<string, { method: string; path: string }>> = {",
  ...Object.entries(operations).map(([id, route]) => `  ${id}: ${JSON.stringify(route)},`),
  "};",
  "",
];
writeFileSync(join(root, "lib", "mocks", "catalog.generated.ts"), lines.join("\n"));
console.log(`catalog: ${files.length} mock files, ${Object.keys(operations).length} operations`);
